export const CITY_MAP = Object.fromEntries(CITIES.map((c) => [c.id, c]));
export const CITY_IDS = CITIES.map((c) => c.id);

export const RACES = {
  "3k": { id: "3k", distance: "3", name: "3K Fun Run", type: "Non Timed Run", minAge: 10, baseFee: 399, totalSlots: 2500 },
  "5k": { id: "5k", distance: "5", name: "5K Fitness Run", type: "Timed Run", minAge: 12, baseFee: 599, totalSlots: 2000 },
  "10k": { id: "10k", distance: "10", name: "10K Challenge", type: "Timed Run", minAge: 16, baseFee: 799, totalSlots: 1500 },
};

export const RACE_IDS = Object.keys(RACES);

export function getCityConfig(cityId) {
  const key = String(cityId || "").trim().toLowerCase();
  return CITY_MAP[key] || CITY_MAP.vadodara;
}

export function getRaceConfig(raceId) {
  const key = String(raceId || "").trim().toLowerCase();
  return RACES[key] || RACES["5k"];
}

export function getFeeInr(cityId, raceId) {
  const city = getCityConfig(cityId);
  const raceKey = String(raceId || "5k").trim().toLowerCase();
  if (city?.fees && city.fees[raceKey] !== undefined) {
    return city.fees[raceKey];
  }
  return getRaceConfig(raceKey).baseFee;
}

export function raceLabel(raceId) {
  const key = String(raceId || "").trim().toLowerCase();
  if (RACES[key]) return RACES[key].name;
  if (key === "21k") return "Half Marathon (21K)";
  return "5K Fitness Run";
}

export function cityLabel(cityId) {
  const key = String(cityId || "").trim().toLowerCase();
  if (CITY_MAP[key]) return CITY_MAP[key].name;
  return key ? key.charAt(0).toUpperCase() + key.slice(1) : "Vadodara";
}

export function getVenue(cityId) {
  return getCityConfig(cityId).venue;
}

export function getCityDate(cityId) {
  return getCityConfig(cityId).date;
}

export function getCityDateISO(cityId) {
  return getCityConfig(cityId).dateISO;
}

